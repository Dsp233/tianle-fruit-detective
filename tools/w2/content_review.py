def option_set(q, correct, wrong):
    # Preserve the original balanced answer position. The runtime also shuffles
    # displayed choices; the stored first-answer index remains stable.
    if len({correct,*wrong})!=3:
        raise ValueError("duplicate choice "+q["id"])
    out=list(wrong);out.insert(q["answer"],correct);q["options"]=out

def classified(q, category, ability, error_type, basis):
    q.update(category=category,ability=ability,errorType=error_type,
             classification={"status":"design_reviewed","basis":basis},
             metadataStatus="reviewed",targetWords=[])
    q.pop("proposedDesignSlot",None)

def new_panels(text,kind):
    # Neutral presentation for the diagnostic; no clue-bearing art.
    # Quiz uses paragraph text joined exactly, and the existing media module
    # reads the original passage. No change to W1 illustrations.
    pieces=re.findall(r'[^。！？]+[。！？]?|[。！？]',text)
    assert "".join(pieces)==text
    return [{"text":p,"scene":"library","action":"read","prop":"book","cast":["tianle","xiaohe","tuantuan"]} for p in pieces]

def review(draft,base):
    sets=copy.deepcopy(draft["sets"])
    ledger=[]
    assert len(STORY)==len(MATH)==len(sets)==13
    for i,(s,legacy) in enumerate(zip(sets,base["diagnostics"]["sets"])):
        assert len(s["forms"])==len(STORY[i])==len(MATH[i])==4
        bp=copy.deepcopy(legacy["blueprint"])
        assert bp["mathKnowledge"]
        bp["equatingStatus"]="BLUEPRINT_MATCHED_NOT_EMPIRICALLY_EQUATED"
        bp["reviewScope"]="AI design review; no empirical equating or child results."
        bp["referenceLegacySet"]=legacy["id"]
        s.update(metadataStatus="reviewed",availability="enabled_reviewed_candidate",blueprint=bp)
        for j,f in enumerate(s["forms"]):
            story,math=f["materials"]
            q1,q2=story["questions"]
            fact,inference,anchor,reason,w1,w2=STORY[i][j]
            # All facts and unedited inference answers must match the recovered
            # authored draft; changed items retain a trace to their original.
            assert q1["options"][q1["answer"]]==fact,(q1["id"],fact)
            edit=STORY_EDITS.get((i,j),{})
            original_inference=q2["options"][q2["answer"]]
            if "text" in edit:
                old,new=edit["text"]
                assert old in story["text"]
                story["text"]=story["text"].replace(old,new)
            if "title" in edit: story["title"]=edit["title"]
            if "fact_prompt" in edit:q1["prompt"]=edit["fact_prompt"]
            if "fact_wrong" in edit:option_set(q1,fact,edit["fact_wrong"])
            if "inference_prompt" in edit:q2["prompt"]=edit["inference_prompt"]
            if original_inference!=inference and (i,j) not in {(3,1),(8,0)}:
                raise ValueError("unreviewed answer change "+q2["id"])
            assert anchor in story["text"],(q1["id"],anchor)
            q1["evidence"]=[anchor]
            q1["explanation"]="原文写着“"+anchor+"”，据此核对答案。"
            q2["evidence"]=[story["text"]]
            q2["explanation"]=reason
            option_set(q2,inference,[w1,w2])
            classified(q1,"reading","facts","information","directly stated fact")
            classified(q2,"reading","inference","sentence","inference supported by passage")
            story.update(goal="从原文提取事实，并依据前后文作出推断。",tags=["诊断未见材料","事实与推断"],prerequisites=[],prerequisitesStatus="reviewed",metadataStatus="reviewed",difficulty=legacy["forms"][j]["materials"][0]["difficulty"],panels=new_panels(story["text"],"story"))
            story.pop("proposedPrerequisites",None)
            mq1,mq2=math["questions"]
            mt,cp,ca,cw1,cw2,n,u,d1,d2,calc=MATH[i][j]
            assert math["model"]["result"]==n and math["model"]["unit"]==u,(mq2["id"],n,u)
            assert mq2["options"][mq2["answer"]]==str(n)+u
            math["text"]=mt
            mq1["prompt"]=cp
            option_set(mq1,ca,[cw1,cw2])
            mq1["evidence"]=[mt];mq1["explanation"]="按原文辨认数量和限制："+ca+"。"
            mq2["evidence"]=[mt];mq2["explanation"]=calc
            option_set(mq2,str(n)+u,[str(d1)+u,str(d2)+u])
            classified(mq1,"math","conditions","information","explicit numerical condition")
            classified(mq2,"math","model","calculation","numerical model; tag is not diagnosed cause")
            math["model"]["status"]="reviewed"
            math.update(goal="独立识别数量条件，再建立已学数学关系。",tags=["诊断未见材料","条件与建模"],prerequisites=copy.deepcopy(bp["mathKnowledge"]),prerequisitesStatus="reviewed",metadataStatus="reviewed",difficulty=legacy["forms"][j]["materials"][1]["difficulty"],panels=new_panels(mt,"math"))
            math.pop("proposedPrerequisites",None)
            ledger.append({"setId":s["id"],"formId":f["id"],"week":i,
              "questions":[{"id":q1["id"],"answer":fact,"basis":anchor},
                           {"id":q2["id"],"answer":inference,"basis":reason,"distractors":[w1,w2]},
                           {"id":mq1["id"],"answer":ca,"basis":mt,"distractors":[cw1,cw2]},
                           {"id":mq2["id"],"answer":str(n)+u,"basis":calc,"distractors":[str(d1)+u,str(d2)+u]}],
              "prerequisites":bp["mathKnowledge"],"designLimits":"Four parallel forms target the same reading and numerical-relation slots, not empirically equated."})
    return sets,ledger
